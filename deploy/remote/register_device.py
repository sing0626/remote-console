"""Register another owned phone behind the existing HTTPS gateway.

Run on the VPS. Existing primary credentials and certificates are retained.
Only the phone's public enrollment key is required.
"""
from pathlib import Path
import argparse, hashlib, json, os, re, secrets, socket, subprocess, tempfile


def setting(text, name):
    matches = re.findall(r'^'+re.escape(name)+r'\s*=\s*([^\r\n]+)\s*$', text, re.M)
    if len(matches) != 1:
        raise ValueError('Missing or duplicate setting: '+name)
    return matches[0].strip().strip('"')


def public_key(path):
    data = Path(path).read_bytes()
    def openssl(*args):
        return subprocess.run(['openssl','pkey','-pubin',*args], input=data, capture_output=True, check=True).stdout
    description = openssl('-text','-noout').decode('ascii')
    bits = re.search(r'\((\d+) bit\)', description)
    if not bits or int(bits[1]) < 3072:
        raise ValueError('An RSA public enrollment key of at least 3072 bits is required')
    # EC public keys can also be parsed by openssl pkey; reject them explicitly.
    if 'Modulus:' not in description:
        raise ValueError('Use the RSA enrollment public key generated by the phone')
    der = openssl('-pubout','-outform','DER')
    return openssl('-pubout','-outform','PEM'), hashlib.sha256(der).hexdigest()


def atomic_write(path, data):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as f:
        temp = Path(f.name); f.write(data.encode('utf-8') if isinstance(data,str) else data)
    temp.chmod(0o600); os.replace(temp, path)


def free_port(start, occupied, check):
    for port in range(start, start+100):
        if port in occupied:
            continue
        if check:
            try:
                with socket.socket() as sock:
                    sock.bind(('0.0.0.0',port))
            except OSError:
                continue
        occupied.add(port)
        return port
    raise ValueError('No free per-device tunnel port in the allocation range')


def register(base, primary_key, device_id, name, key_path, compose_path, check_ports=True):
    base = Path(base).resolve(); compose_path = Path(compose_path).resolve()
    if not re.fullmatch(r'[a-z][a-z0-9_-]{0,31}',device_id) or device_id in ['primary','tunnel']:
        raise ValueError('Choose a separate stable device ID')
    if not name.strip() or len(name)>80:
        raise ValueError('Use a nonempty phone name of at most 80 characters')
    os.umask(0o077)
    root_phone = (base/'phone-frpc.toml').read_text(encoding='utf-8')
    domain, ip = setting(root_phone,'transport.tls.serverName'), setting(root_phone,'serverAddr')
    if not re.fullmatch(r'[a-z0-9][a-z0-9.-]+',domain):
        raise ValueError('Invalid existing HTTPS server identity')
    registry_path = base/'devices.json'
    if registry_path.exists():
        cfg = json.loads(registry_path.read_text(encoding='utf-8'))
        if cfg.get('version')!=1 or not cfg.get('devices') or cfg.get('default_device')!='primary':
            raise ValueError('Unknown device registry was preserved')
    else:
        raise ValueError('Initialize this deployment with initialize.py before registering another phone')
    ids = [item['id'] for item in cfg['devices']]
    if len(set(ids))!=len(ids) or len(ids)>=32 and device_id not in ids:
        raise ValueError('Invalid or full device registry was preserved')
    if compose_path.exists():
        existing = json.loads(compose_path.read_text(encoding='utf-8'))
        if existing.get('x-remoteconsole-generated')!=1:
            raise ValueError('Unknown additional Compose configuration was preserved')
    key, fingerprint = public_key(key_path)
    profile = base/'devices'/device_id
    existing = next((d for d in cfg['devices'] if d['id']==device_id),None)
    if existing:
        if existing['private']!='/private/devices/'+device_id or existing['key']!='/private/devices/'+device_id+'/enrollment.pub':
            raise ValueError('Existing device mapping was preserved')
        _, old_fingerprint = public_key(profile/'enrollment.pub')
        if old_fingerprint!=fingerprint:
            raise ValueError('Device ID is already paired with a different key; existing identity was preserved')
        for file in ['frps.toml','phone-frpc.toml','ice.private.json','pki/ca.crt']:
            if not (profile/file).is_file():
                raise ValueError('Incomplete existing profile was preserved: '+file)
    else:
        if profile.exists():
            raise ValueError('Unrecognized existing device directory was preserved')
        if len(cfg['devices'])>=32:
            raise ValueError('Device registry is full')
        tunnel_ports={int(setting((base/'frps.toml').read_text(encoding='utf-8'),'bindPort'))}
        proxy_ports={18079,18081}
        for item in cfg['devices']:
            if item['id']=='primary':continue
            child=base/'devices'/item['id']
            tunnel_ports.add(int(setting((child/'frps.toml').read_text(encoding='utf-8'),'bindPort')))
            proxy_ports.add(int(setting((child/'phone-frpc.toml').read_text(encoding='utf-8'),'remotePort')))
        tunnel=free_port(7001,tunnel_ports,check_ports); proxy=free_port(18082,proxy_ports,check_ports)
        token=secrets.token_urlsafe(40)
        profile.mkdir(parents=True,mode=0o700);(profile/'pki').mkdir(mode=0o700)
        atomic_write(profile/'enrollment.pub',key)
        atomic_write(profile/'pki/ca.crt',(base/'pki/ca.crt').read_bytes())
        atomic_write(profile/'ice.private.json',(base/'ice.private.json').read_bytes())
        atomic_write(profile/'frps.toml',f'''bindPort = {tunnel}
proxyBindAddr = "127.0.0.1"
auth.method = "token"
auth.token = "{token}"
auth.additionalScopes = ["HeartBeats", "NewWorkConns"]
allowPorts = [{{ single = {proxy} }}]
transport.tls.force = true
transport.tls.certFile = "/pki/server.crt"
transport.tls.keyFile = "/pki/server.key"
''')
        atomic_write(profile/'phone-frpc.toml',f'''serverAddr = "{ip}"
serverPort = {tunnel}
auth.method = "token"
auth.token = "{token}"
auth.additionalScopes = ["HeartBeats", "NewWorkConns"]
transport.tls.enable = true
transport.tls.serverName = "{domain}"
transport.tls.trustedCaFile = "/data/local/tmp/remote-console/remote/ca.crt"
[[proxies]]
name = "remote-console-{device_id}"
type = "tcp"
localIP = "127.0.0.1"
localPort = 8079
remotePort = {proxy}
''')
        cfg['devices'].append({'id':device_id,'name':name,'upstream':f'http://127.0.0.1:{proxy}','key':f'/private/devices/{device_id}/enrollment.pub','private':f'/private/devices/{device_id}'})
    services={}
    for item in cfg['devices']:
        ident=item['id']
        if ident=='primary':continue
        if not re.fullmatch(r'[a-z][a-z0-9_-]{0,31}',ident) or ident=='tunnel':
            raise ValueError('Invalid existing additional device ID')
        services['signaling-'+ident]={'build':{'context':'.','dockerfile':'frps.Dockerfile'},'restart':'unless-stopped','network_mode':'host','volumes':[f'./private/devices/{ident}/frps.toml:/etc/frp/frps.toml:ro','./private/pki:/pki:ro']}
    atomic_write(compose_path,json.dumps({'x-remoteconsole-generated':1,'services':services},indent=2)+'\n')
    if registry_path.exists() and not (base/'devices.json.pre-multihost').exists():
        atomic_write(base/'devices.json.pre-multihost',registry_path.read_bytes())
    atomic_write(registry_path,json.dumps(cfg,indent=2)+'\n')
    tunnel=int(setting((profile/'frps.toml').read_text(encoding='utf-8'),'bindPort'))
    return {'device_id':device_id,'name':existing['name'] if existing else name,'entry':'https://'+domain+'/control','public_tcp_port':tunnel,'services':list(services),'public_key_fingerprint':fingerprint,'existing_primary_credentials_preserved':True}


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--private',type=Path,default=Path('private'))
    parser.add_argument('--primary-key',type=Path,default=Path('private/enrollment.pub'))
    parser.add_argument('--id',required=True);parser.add_argument('--name',required=True)
    parser.add_argument('--public-key',required=True,type=Path)
    parser.add_argument('--compose',type=Path,default=Path('compose.devices.generated.json'))
    args=parser.parse_args()
    try:
        result=register(args.private,args.primary_key,args.id,args.name,args.public_key,args.compose)
    except (ValueError,OSError,subprocess.CalledProcessError,KeyError) as error:
        raise SystemExit(str(error))
    print(json.dumps(result,indent=2))
